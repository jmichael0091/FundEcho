/**
 * Normalizes funder name or slug
 */
export function getFunderBySlug(slug: string): FunderProfile | undefined {
  const clean = slug.toLowerCase().trim();
  return VERIFIED_FUNDERS.find((f) => f.slug === clean || f.id === clean);
}

/**
 * Finds matching funder by matching organization string
 */
export function getFunderByOrganizationName(orgName: string): FunderProfile | undefined {
  if (!orgName) return undefined;
  const cleanOrg = orgName.toLowerCase();

  return VERIFIED_FUNDERS.find((f) => {
    const fName = f.name.toLowerCase();
    const fAcronym = f.acronym ? f.acronym.toLowerCase() : '';
    return (
      cleanOrg.includes(fName) ||
      fName.includes(cleanOrg) ||
      (fAcronym && cleanOrg.includes(fAcronym))
    );
  });
}

/**
 * Returns all verified funders
 */
export function getAllFunders(): FunderProfile[] {
  return VERIFIED_FUNDERS;
}
