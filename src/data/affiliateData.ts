const AFFILIATES_STORAGE_KEY = 'fundora_affiliate_offers_v1';

export function getStoredAffiliateOffers(): AffiliateOffer[] {
  try {
    const raw = localStorage.getItem(AFFILIATES_STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(AFFILIATES_STORAGE_KEY, JSON.stringify(DEMO_AFFILIATE_OFFERS));
      return DEMO_AFFILIATE_OFFERS;
    }
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
    return DEMO_AFFILIATE_OFFERS;
  } catch (e) {
    console.error('Failed reading affiliate offers from localStorage:', e);
    return DEMO_AFFILIATE_OFFERS;
  }
}

export function saveAffiliateOffer(offer: AffiliateOffer): void {
  try {
    const current = getStoredAffiliateOffers();
    const index = current.findIndex((o) => o.id === offer.id);
    let updated: AffiliateOffer[];
    if (index >= 0) {
      updated = [...current];
      updated[index] = { ...offer, updatedAt: new Date().toISOString() };
    } else {
      updated = [{ ...offer, createdAt: new Date().toISOString(), updatedAt: new Date().toISOString() }, ...current];
    }
    localStorage.setItem(AFFILIATES_STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error('Failed saving affiliate offer:', e);
  }
}

export function toggleAffiliateOfferStatus(offerId: string): AffiliateOffer | null {
  try {
    const current = getStoredAffiliateOffers();
    const index = current.findIndex((o) => o.id === offerId);
    if (index >= 0) {
      const newStatus = current[index].status === 'Active' ? 'Inactive' : 'Active';
      current[index] = {
        ...current[index],
        status: newStatus,
        updatedAt: new Date().toISOString()
      };
      localStorage.setItem(AFFILIATES_STORAGE_KEY, JSON.stringify(current));
      return current[index];
    }
  } catch (e) {
    console.error('Failed toggling affiliate offer status:', e);
  }
  return null;
}

export function deleteAffiliateOffer(offerId: string): void {
  try {
    const current = getStoredAffiliateOffers();
    const filtered = current.filter((o) => o.id !== offerId);
    localStorage.setItem(AFFILIATES_STORAGE_KEY, JSON.stringify(filtered));
  } catch (e) {
    console.error('Failed deleting affiliate offer:', e);
  }
}

export function resetAffiliateOffersToDefaults(): AffiliateOffer[] {
  try {
    localStorage.setItem(AFFILIATES_STORAGE_KEY, JSON.stringify(DEMO_AFFILIATE_OFFERS));
  } catch (e) {
    console.error('Failed resetting affiliate offers:', e);
  }
  return DEMO_AFFILIATE_OFFERS;
}
